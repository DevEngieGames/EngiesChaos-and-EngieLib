import net.minecraft.network.chat.Component;

import java.util.List;

public class YouAreNotSupposedToHaveThisItem extends Item {
	public YouAreNotSupposedToHaveThisItem() {
		super(new Item.Properties().tab(null).rarity(Rarity.EPIC));
	}

	@Override
	public void appendHoverText(ItemStack itemstack, Level level, List<Component> list, TooltipFlag flag) {
		super.appendHoverText(itemstack, level, list, flag);
		list.add(Component.translatable("item.allaboutengie.you_are_not_supposed_to_have_this.description_0"));
	}
}